// Flattened plain-text rendering, used to feed the AI system prompt —
// Gemini's systemInstruction field just wants a string, not structured JSX.
export function renderPolicyAsText(): string {
  const facts = QUICK_FACTS.map(f => `- ${f.label}: ${f.value}`).join('\n')
  const sections = POLICY_SECTIONS.map(s => `## ${s.title}\n${s.body.join('\n')}`).join('\n\n')
  return (
    'ข้อบังคับเกี่ยวกับการทำงาน (ใช้ร่วมกันทั้งบริษัท เซฟคอน และ ไฮคอน มีผลบังคับใช้ตั้งแต่วันที่ 1 มกราคม 2569):\n\n' +
    '### สรุปตัวเลขสำคัญ\n' + facts + '\n\n' +
    '### เนื้อหาเต็ม\n' + sections
  )
}
